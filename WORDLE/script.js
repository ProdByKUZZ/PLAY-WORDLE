    // === FRIEND WORD SYSTEM ===

    createFriendWord() {
        const input = document.getElementById('friendWordInput');
        const word = input.value.toUpperCase().trim();

        // Validation
        if (word.length !== 5) {
            this.showNotification('Слово должно состоять из 5 букв!', 'error');
            return;
        }

        if (!/^[А-ЯЁ]+$/.test(word)) {
            this.showNotification('Используйте только русские буквы!', 'error');
            return;
        }

        if (!this.words.includes(word)) {
            this.showNotification('Этого слова нет в словаре!', 'error');
            return;
        }

        // Create unique ID and save word
        const wordId = this.generateWordId();
        this.saveFriendWord(wordId, word);
        
        // Create shareable link
        const baseUrl = window.location.origin + window.location.pathname;
        const link = `${baseUrl}?friend=${wordId}`;

        // Show link section
        document.getElementById('friendLink').value = link;
        document.getElementById('friendLinkContainer').style.display = 'block';

        // Update statistics
        this.stats.wordsCreated++;
        this.saveStats();
        this.updateFriendStatsDisplay();
        
        // Clear input
        input.value = '';
        
        this.showNotification('Слово создано! Отправьте ссылку другу.', 'success');
    }

    generateWordId() {
        return Date.now().toString(36) + Math.random().toString(36).substr(2, 5);
    }

    saveFriendWord(wordId, word) {
        const friendWords = JSON.parse(localStorage.getItem('wordleFriendWords') || '{}');
        friendWords[wordId] = {
            word: word,
            createdAt: new Date().toISOString(),
            createdBy: this.stats.userId,
            guessedCount: 0,
            guesses: []
        };
        localStorage.setItem('wordleFriendWords', JSON.stringify(friendWords));
    }

    checkFriendWord() {
        const urlParams = new URLSearchParams(window.location.search);
        const friendWordId = urlParams.get('friend');
        
        if (friendWordId) {
            const friendWords = JSON.parse(localStorage.getItem('wordleFriendWords') || '{}');
            const friendWordData = friendWords[friendWordId];
            
            if (friendWordData && this.words.includes(friendWordData.word)) {
                this.friendWord = friendWordData.word;
                this.friendWordId = friendWordId;
                
                console.log('Playing with friend word:', this.friendWord);
                
                // Update guess count
                friendWordData.guessedCount = (friendWordData.guessedCount || 0) + 1;
                friendWords[friendWordId] = friendWordData;
                localStorage.setItem('wordleFriendWords', JSON.stringify(friendWords));
                
                // Update global statistics
                this.updateWordsGuessedStats();
                
                this.showNotification(`Вы отгадываете слово друга!`, 'success');
            } else {
                this.showNotification('Слово не найдено или было удалено', 'error');
            }
        }
    }

    updateWordsGuessedStats() {
        const friendWords = JSON.parse(localStorage.getItem('wordleFriendWords') || '{}');
        let totalGuessed = 0;
        
        Object.values(friendWords).forEach(wordData => {
            if (wordData.createdBy === this.stats.userId) {
                totalGuessed += wordData.guessedCount || 0;
            }
        });
        
        this.stats.wordsGuessedByFriends = totalGuessed;
        this.saveStats();
    }

